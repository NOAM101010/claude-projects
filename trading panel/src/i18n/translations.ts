/** מזהה שפת ברירת מחדל בביקור ראשון לפי `navigator.language`. */
export function detectDefaultLanguage(navigatorLanguage: string | undefined): Language {
  const lang = (navigatorLanguage ?? '').toLowerCase()
  if (lang.startsWith('he')) return 'he'
  if (lang.startsWith('es')) return 'es'
  if (lang.startsWith('fr')) return 'fr'
  return 'en'
}

/** מחליף placeholders מהצורה {{name}} במחרוזת תרגום. */
export function interpolate(template: string, params?: Record<string, string | number>): string {
  if (!params) return template
  return template.replace(/\{\{(\w+)\}\}/g, (match, key: string) => {
    const value = params[key]
    return value === undefined ? match : String(value)
  })
}

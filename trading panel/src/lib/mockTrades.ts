import { computePnl } from './stats'
import type { Trade } from '../types/trade'

/**
 * דאטה מדומה בזיכרון בלבד (לא localStorage, לא רשת) - לשלב הזה בלבד עד שהסכמה
 * ב-Supabase תורץ בפועל. מגוון כיוונים/מטבעות/סגנונות/תאריכים (פרושים על 2025-2026)
 * כדי שהדשבורד (כולל מפת החום השנתית והרצפים) ייראה משכנע בהדגמה.
 */
function trade(input: Omit<Trade, 'id' | 'pnl'>): Trade {
  const pnl = computePnl({
    direction: input.direction,
    entryPrice: input.entryPrice,
    exitPrice: input.exitPrice,
    quantity: input.quantity,
    fee: input.fee,
  })
  return { ...input, id: crypto.randomUUID(), pnl }
}

